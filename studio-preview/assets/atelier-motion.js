/* APTITUD LABS / Motion Direction
   Independent visual layer. Never touches checkout, quotation totals or form data.
   All motion progressively enhances existing content; scrolling remains native. */
(() => {
  'use strict';
  const root=document.body;
  if(!root || !root.classList.contains('al-theme'))return;
  const reduce=window.matchMedia('(prefers-reduced-motion: reduce)');
  const precise=window.matchMedia('(hover:hover) and (pointer:fine)');
  if(reduce.matches)return;

  root.classList.add('al-motion-enabled');
  const $=(s,from=document)=>from.querySelector(s);
  const $$=(s,from=document)=>Array.from(from.querySelectorAll(s));
  const clamp=(v,lo,hi)=>Math.min(hi,Math.max(lo,v));

  // Scroll progress: 2px and a calmer header. No sticky chapters or scroll locking.
  const header=$('.al-header');
  if(header){
    const indicator=document.createElement('div');
    indicator.className='al-motion-progress';
    indicator.setAttribute('aria-hidden','true');
    header.appendChild(indicator);
  }

  // Reveals work on semantic elements without cloning text or editing headings.
  const observed=new WeakSet();
  const entryObserver=('IntersectionObserver' in window)?new IntersectionObserver((records,observer)=>{
    for(const record of records){
      if(!record.isIntersecting)continue;
      record.target.classList.add('al-motion-visible');
      observer.unobserve(record.target);
    }
  },{rootMargin:'110px 0px 110px 0px',threshold:0}):null;

  function observeElement(el,kind,delay=0){
    if(!el||observed.has(el))return;
    observed.add(el);
    el.classList.add(kind);
    if(delay)el.style.setProperty('--al-motion-delay',delay+'ms');
    if(entryObserver)entryObserver.observe(el);
    else el.classList.add('al-motion-visible');
  }

  $$('.al-title,.al-section-title').forEach((el,i)=>{
    observeElement(el,'al-motion-heading',i===0?0:0);
  });
  $$('.al-section').forEach(el=>observeElement(el,'al-motion-section'));
  $$('.al-section-head .al-section-copy,.al-feature-strip article,.al-form-shell,.al-band,.al-terms details').forEach((el,i)=>{
    observeElement(el,'al-motion-copy',i%3===0?40:i%3===1?110:170);
  });
  const cardsSelector='.al-service-tile,.al-work-card,.al-price-card,.al-choice';
  function enhanceCards(scope=document){
    $$(cardsSelector,scope).forEach((el,i)=>{
      observeElement(el,'al-motion-card',Math.min((i%4)*65,195));
      el.classList.add('al-motion-tilt');
    });
  }
  enhanceCards();

  // Covers generated by NFC's own code. No edits to its state or cart logic.
  const catalog=$('#nfc-products');
  if(catalog){
    const enhanceProducts=()=>{
      $$('.nfc-product',catalog).forEach((el,i)=>{
        observeElement(el,'al-motion-card',(i%3)*55);
        el.classList.add('al-motion-tilt');
      });
    };
    enhanceProducts();
    new MutationObserver(enhanceProducts).observe(catalog,{childList:true});
  }

  // Photographic 'shutter' wipes and parallax with an active-scene budget.
  const scenes=$$('.al-photograph');
  const active=new Set();
  const heroPhoto=$('.al-hero-photo');
  const sceneObserver=('IntersectionObserver' in window)?new IntersectionObserver((records)=>{
    for(const rec of records){
      if(rec.isIntersecting)active.add(rec.target);
      else active.delete(rec.target);
    }
    queueTick();
  },{rootMargin:'120px 0px 120px 0px',threshold:0}):null;
  scenes.forEach((photo,i)=>{
    photo.classList.add('al-motion-photo');
    if(photo===heroPhoto)photo.classList.add('al-motion-hero-depth');
    else{
      photo.style.setProperty('--al-motion-delay',Math.min((i%3)*60,120)+'ms');
      // Don't hide the actual image before the visitor can scroll to it.
      if('IntersectionObserver' in window){
        const photoObserver=new IntersectionObserver((entries,observer)=>{
          entries.forEach(e=>{
            if(!e.isIntersecting)return;
            e.target.classList.add('al-motion-photo-seen');
            observer.unobserve(e.target);
          });
        },{rootMargin:'0px 0px -5% 0px',threshold:.04});
        photoObserver.observe(photo);
      }else photo.classList.add('al-motion-photo-seen');
    }
    if(sceneObserver)sceneObserver.observe(photo);
    else active.add(photo);
  });

  // A single animation frame can handle all scroll states across the entire page.
  let tickPending=false,documentHeight=1,lastScroll=window.scrollY||0;
  function queueTick(){
    if(tickPending||reduce.matches)return;
    tickPending=true;
    window.requestAnimationFrame(tick);
  }
  function tick(){
    tickPending=false;
    if(reduce.matches)return;
    const y=window.scrollY||document.documentElement.scrollTop||0;
    const vw=window.innerHeight||780;
    documentHeight=Math.max(1,document.documentElement.scrollHeight-vw);
    if(header){
      header.style.setProperty('--al-document-progress',clamp(y/documentHeight,0,1).toFixed(4));
      header.classList.toggle('al-header-moving',y>38);
    }
    for(const photo of active){
      if(!photo.isConnected)continue;
      const rect=photo.getBoundingClientRect();
      if(rect.bottom<-150||rect.top>vw+150)continue;
      const center=rect.top+rect.height*.5;
      const relative=clamp((center-vw*.5)/vw,-1.1,1.1);
      const depth=photo===heroPhoto?20:28;
      const offset=clamp(-relative*depth,-24,24);
      photo.style.setProperty('--al-photo-drift',offset.toFixed(2)+'px');
      if(photo===heroPhoto && !precise.matches){
        photo.style.setProperty('--al-hero-rotation',(relative*1.7).toFixed(2)+'deg');
      }
    }
    lastScroll=y;
  }
  window.addEventListener('scroll',queueTick,{passive:true});
  window.addEventListener('resize',queueTick,{passive:true});
  queueTick();

  // Spring-like perspective tilt and understated local specular light.
  // Only on real mouse/trackpad; no touch pointermove handlers.
  const tilts=$$('.al-motion-tilt');
  function prepareTilt(card){
    if(card.dataset.alMotionTiltWired==='1')return;
    card.dataset.alMotionTiltWired='1';
    let pointerFrame=0,pointerX=0,pointerY=0;
    function draw(){
      pointerFrame=0;
      if(!precise.matches||reduce.matches||!card.classList.contains('al-motion-visible'))return;
      const b=card.getBoundingClientRect();
      const nx=clamp((pointerX-b.left)/Math.max(1,b.width),0,1);
      const ny=clamp((pointerY-b.top)/Math.max(1,b.height),0,1);
      const rx=(.5-ny)*5.4,ry=(nx-.5)*6.4;
      card.style.setProperty('--al-tilt-x',rx.toFixed(2)+'deg');
      card.style.setProperty('--al-tilt-y',ry.toFixed(2)+'deg');
      card.style.setProperty('--al-shine-x',(nx*100).toFixed(1)+'%');
      card.style.setProperty('--al-shine-y',(ny*100).toFixed(1)+'%');
    }
    card.addEventListener('pointerenter',e=>{
      if(!precise.matches||e.pointerType==='touch')return;
      card.style.willChange='transform';
    });
    card.addEventListener('pointermove',e=>{
      if(!precise.matches||e.pointerType==='touch')return;
      pointerX=e.clientX;pointerY=e.clientY;
      if(!pointerFrame)pointerFrame=requestAnimationFrame(draw);
    },{passive:true});
    card.addEventListener('pointerleave',()=>{
      if(pointerFrame)cancelAnimationFrame(pointerFrame);
      pointerFrame=0;
      card.style.setProperty('--al-tilt-x','0deg');
      card.style.setProperty('--al-tilt-y','0deg');
      card.style.removeProperty('will-change');
    });
  }
  tilts.forEach(prepareTilt);
  if(catalog){
    // Product cards are inserted asynchronously by the existing NFC module.
    new MutationObserver(()=>{
      $$('.nfc-product.al-motion-tilt',catalog).forEach(prepareTilt);
    }).observe(catalog,{childList:true});
    $$('.nfc-product.al-motion-tilt',catalog).forEach(prepareTilt);
  }

  // Magnetic CTAs: displacement never exceeds 5px and never alters focus state.
  $$('.al-actions .al-btn,.al-band .al-btn,.al-form-shell > div > .al-btn').forEach(btn=>{
    btn.classList.add('al-motion-magnetic');
    btn.addEventListener('pointermove',e=>{
      if(!precise.matches||e.pointerType==='touch'||reduce.matches)return;
      const r=btn.getBoundingClientRect();
      const x=clamp((e.clientX-r.left-r.width/2)*.09,-5,5);
      const y=clamp((e.clientY-r.top-r.height/2)*.12,-5,5);
      btn.style.setProperty('--al-magnet-x',x.toFixed(1)+'px');
      btn.style.setProperty('--al-magnet-y',y.toFixed(1)+'px');
    },{passive:true});
    btn.addEventListener('pointerleave',()=>{
      btn.style.setProperty('--al-magnet-x','0px');
      btn.style.setProperty('--al-magnet-y','0px');
    });
  });

  // If accessibility preference is changed while the page is open,
  // immediately clear active effects rather than trapping invisible content.
  reduce.addEventListener?.('change',e=>{
    if(!e.matches)return;
    root.classList.remove('al-motion-enabled');
    entryObserver?.disconnect();
    sceneObserver?.disconnect();
    $$('.al-motion-heading,.al-motion-copy,.al-motion-card,.al-motion-section').forEach(el=>el.classList.add('al-motion-visible'));
    scenes.forEach(photo=>{
      photo.classList.add('al-motion-photo-seen');
      photo.style.removeProperty('--al-photo-drift');
      photo.style.removeProperty('--al-hero-rotation');
    });
  });
})();
